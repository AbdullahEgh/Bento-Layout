#!/bin/bash
set -euo pipefail
mac_root="$(cd "$(dirname "$0")/.." && pwd)"
repo_root="$(cd "$mac_root/.." && pwd)"
release_tag="${1:?Usage: prepare-update.sh macos-vX.Y.Z}"
[[ "$release_tag" =~ ^macos-v[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo 'Use a macos-vX.Y.Z tag.' >&2; exit 1; }
[[ -z "$(git -C "$repo_root" status --porcelain)" ]] || { echo 'Commit the release source before preparing an OTA update.' >&2; exit 1; }
output_dir="${BENTO_ARTIFACTS_DIR:-$repo_root/artifacts/macos}"
app="$output_dir/Bento.app"
archive="$output_dir/Bento-macos-universal.zip"
[[ -f "$archive" ]] || { echo 'Build the universal OTA release first.' >&2; exit 1; }
[[ "$(/usr/libexec/PlistBuddy -c 'Print :BentoDevelopmentBuild' "$app/Contents/Info.plist")" == 'false' ]] || { echo 'Development builds cannot be published for OTA.' >&2; exit 1; }
version="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$app/Contents/Info.plist")"
[[ "$release_tag" == "macos-v$version" ]] || { echo 'Release tag and app version differ.' >&2; exit 1; }
/usr/bin/codesign --verify --deep --strict "$app"
if [[ -n "${BENTO_NOTARY_PROFILE:-}" ]]; then
  /usr/bin/xcrun notarytool submit "$archive" --keychain-profile "$BENTO_NOTARY_PROFILE" --wait
  /usr/bin/xcrun stapler staple "$app"
  /usr/bin/ditto -c -k --keepParent "$app" "$archive"
  /usr/bin/xcrun stapler validate "$app"
  /usr/sbin/spctl --assess --type execute "$app"
fi
stage="$output_dir/update"
mkdir -p "$stage"
cp "$archive" "$stage/Bento-macos-universal.zip"
sign_options=(--account "${BENTO_ED_KEY_ACCOUNT:-com.abdullahegh.bento}")
if [[ -n "${BENTO_ED_KEY_FILE:-}" ]]; then sign_options+=(--ed-key-file "$BENTO_ED_KEY_FILE"); fi
sign_log="$(mktemp "${TMPDIR:-/tmp}/bento-sign.XXXXXX")"
chmod 600 "$sign_log"
trap 'rm -f "$sign_log"' EXIT
if ! "$mac_root/.build/artifacts/macos/Sparkle/bin/generate_appcast" ${sign_options[@]+"${sign_options[@]}"} \
  --download-url-prefix "https://github.com/AbdullahEgh/Bento-Layout/releases/download/$release_tag/" \
  --maximum-deltas 0 -o "$stage/appcast.xml" "$stage" > "$sign_log" 2>&1; then
  echo 'Sparkle could not sign the update. Check the release key and app configuration.' >&2; exit 1
fi
if ! "$mac_root/.build/artifacts/macos/Sparkle/bin/sign_update" --verify ${sign_options[@]+"${sign_options[@]}"} "$stage/appcast.xml" > "$sign_log" 2>&1; then
  echo 'Sparkle feed signature verification failed.' >&2; exit 1
fi
swift_bin="${BENTO_SWIFT:-$(/usr/bin/xcrun --find swift)}"
"$swift_bin" -module-cache-path "$mac_root/.build/release-tools-cache" "$mac_root/scripts/verify-update.swift" "$app/Contents/Info.plist" "$stage/appcast.xml" "$stage/Bento-macos-universal.zip" "$release_tag"
printf '%s\n' "$release_tag" > "$stage/release-tag"
git -C "$repo_root" rev-parse HEAD > "$stage/source-commit"
(cd "$stage" && shasum -a 256 Bento-macos-universal.zip appcast.xml > update.sha256)
# Feed/notes and archive signatures are generated by Sparkle with the release key.
# Never edit the generated feed after signing it.
printf 'Ready: %s\nPublish the ZIP as a GitHub release asset, then publish appcast.xml on the macos-updates branch.\n' "$stage"
